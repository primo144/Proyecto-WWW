CREATE OR REPLACE PROCEDURE PAYMENTS_SVC.SP_GENERAR_AVISOS_SEMANALES(P_INICIO IN DATE, P_FIN IN DATE) AS
BEGIN
  MERGE INTO PAYMENTS_SVC.WEEKLY_NOTICES T
  USING (
    SELECT E.ID EMPLOYEE_ID,E.CODE EMPLOYEE_CODE,E.EMAIL EMAIL_ADDRESS,
      NVL(SUM(CASE WHEN V.STATUS='EMITIDO' THEN 1 ELSE 0 END),0) VOUCHERS_AVAILABLE,
      NVL(SUM(CASE WHEN V.STATUS='CANJEADO' THEN 1 ELSE 0 END),0) VOUCHERS_USED,
      NVL(SUM(CASE WHEN V.STATUS='IMPRESO' THEN 1 ELSE 0 END),0) VOUCHERS_UNUSED
    FROM CLIENTS_SVC.EMPLOYEES E
    LEFT JOIN ORDERS_SVC.VOUCHERS V ON V.EMPLOYEE_ID=E.ID AND V.VOUCHER_DATE BETWEEN P_INICIO AND P_FIN AND V.STATUS<>'ANULADO'
    WHERE E.ACTIVE=1
    GROUP BY E.ID,E.CODE,E.EMAIL
  ) S ON (T.EMPLOYEE_ID=S.EMPLOYEE_ID AND T.WEEK_START=P_INICIO AND T.WEEK_END=P_FIN)
  WHEN MATCHED THEN UPDATE SET T.EMAIL_ADDRESS=S.EMAIL_ADDRESS,T.VOUCHERS_AVAILABLE=S.VOUCHERS_AVAILABLE,
    T.VOUCHERS_USED=S.VOUCHERS_USED,T.VOUCHERS_UNUSED=S.VOUCHERS_UNUSED,
    T.DELIVERY_STATUS=CASE WHEN T.DELIVERY_STATUS IN ('ENVIADO','ENVIADO_SANDBOX') THEN T.DELIVERY_STATUS ELSE 'PENDIENTE' END,
    T.GENERATED_AT=SYSTIMESTAMP
  WHEN NOT MATCHED THEN INSERT (ID,EMPLOYEE_ID,EMPLOYEE_CODE,EMAIL_ADDRESS,WEEK_START,WEEK_END,VOUCHERS_AVAILABLE,VOUCHERS_USED,VOUCHERS_UNUSED,DELIVERY_STATUS)
    VALUES (LOWER(RAWTOHEX(SYS_GUID())),S.EMPLOYEE_ID,S.EMPLOYEE_CODE,S.EMAIL_ADDRESS,P_INICIO,P_FIN,S.VOUCHERS_AVAILABLE,S.VOUCHERS_USED,S.VOUCHERS_UNUSED,'PENDIENTE');
END;
/

GRANT EXECUTE ON PAYMENTS_SVC.SP_GENERAR_AVISOS_SEMANALES TO PAYMENTS_SVC;
COMMIT;
